<?php

namespace walkerdesigns\multisitecolourswatches\helpers;

use Craft;
use craft\helpers\FileHelper;
use craft\helpers\Json;
use walkerdesigns\multisitecolourswatches\fields\ColourSwatches;
use walkerdesigns\multisitecolourswatches\models\Settings;
use yii\base\InvalidArgumentException;

/** Builds framework theme and safelist files for every colour, shade and opacity editors can choose. */
final class Generator
{
    public const FILES = [
        Frameworks::TAILWIND3 => 'tailwind3.cjs',
        Frameworks::TAILWIND4 => 'tailwind4.css',
        Frameworks::BOOTSTRAP5 => 'bootstrap5.scss',
        Frameworks::PLUGIN => 'plugin.css',
    ];

    private const HEADER = 'Generated by Multisite Colour Swatches. Do not edit: run `php craft multisite-colour-swatches/generate` after changing palettes, fields or settings.';

    /** @var array<string, string> */
    private array $warnings = [];

    /**
     * @param ColourSwatches[]|null $fields Defaults to every Multisite Colour Swatches field.
     * @param string[]|null $sites Site handles; defaults to every site.
     */
    public function __construct(
        private readonly Settings $settings,
        private readonly ?array $fields = null,
        private readonly ?array $sites = null,
    ) {
    }

    /**
     * @param string|null $framework Generate for this framework on every selected site instead of each site's setting.
     * @param string|null $site Only include this site's palettes.
     * @return array{files: array<string, string>, counts: array<string, int>, warnings: string[]}
     */
    public function generate(?string $framework = null, ?string $site = null): array
    {
        if ($framework !== null && !in_array($framework, Frameworks::ALL, true)) {
            throw new InvalidArgumentException("Unknown framework \"$framework\". Use " . implode(', ', Frameworks::ALL) . '.');
        }
        $this->warnings = [];
        $files = [];
        $counts = [];
        foreach ($this->collect($framework, $site) as $name => $tokens) {
            [$files[self::FILES[$name]], $counts[$name]] = match ($name) {
                Frameworks::TAILWIND3 => $this->tailwind3($tokens),
                Frameworks::TAILWIND4 => $this->tailwind4($tokens),
                Frameworks::BOOTSTRAP5 => $this->bootstrap5($tokens),
                Frameworks::PLUGIN => $this->pluginCss($tokens),
            };
        }
        return ['files' => $files, 'counts' => $counts, 'warnings' => array_values($this->warnings)];
    }

    /** @return string[] The files written. */
    public static function write(array $files, string $directory, ?string $suffix = null): array
    {
        $directory = rtrim(Craft::getAlias($directory), '/\\');
        FileHelper::createDirectory($directory);
        $written = [];
        foreach ($files as $name => $contents) {
            if ($suffix !== null && $suffix !== '') {
                $name = preg_replace('/(\.[a-z0-9]+)$/', "-$suffix$1", $name);
            }
            $path = $directory . DIRECTORY_SEPARATOR . $name;
            FileHelper::writeToFile($path, $contents, ['lock' => false]);
            $written[] = $path;
        }
        return $written;
    }

    /** @return array<string, array<string, array>> framework => token => colours, shades and opacities. */
    private function collect(?string $forceFramework, ?string $onlySite): array
    {
        $sites = $this->sites ?? array_map(static fn($site): string => $site->handle, Craft::$app->getSites()->getAllSites());
        if ($onlySite !== null) {
            if (!in_array($onlySite, $sites, true)) {
                throw new InvalidArgumentException("Unknown site \"$onlySite\".");
            }
            $sites = [$onlySite];
        }
        $fields = $this->fields ?? array_values(array_filter(Craft::$app->getFields()->getAllFields(false),
            static fn($field): bool => $field instanceof ColourSwatches));
        $labels = Frameworks::labels();
        $data = [];
        foreach ($sites as $site) {
            $framework = $forceFramework ?? $this->settings->getFrameworkForSite($site);
            foreach ($fields as $field) {
                try {
                    $options = $field->getOptionsForSite($site);
                } catch (\Throwable $exception) {
                    $this->warn("$field->handle: " . $exception->getMessage());
                    continue;
                }
                foreach ($options as $option) {
                    $token = $option->getToken();
                    if ($token === '') {
                        $this->warn("$option->label has no usable class name. Add a \"token\" to the swatch config.");
                        continue;
                    }
                    if ($framework !== Frameworks::PLUGIN && $option->isGradient()) {
                        $this->warn("$labels[$framework]: $option->label is a gradient, so it has no framework classes. Use swatch.cssColor in an inline style instead.");
                        continue;
                    }
                    $stops = array_map([Colour::class, 'normalize'], $option->getStops());
                    $entry = $data[$framework][$token] ?? [
                        'label' => $option->label,
                        'stops' => $stops,
                        'theme' => $option->definesThemeColour(),
                        'shades' => [],
                        'opacities' => [],
                        'site' => $site,
                    ];
                    $conflict = $entry['stops'] !== $stops;
                    foreach ($field->shadeOptionsForFramework($framework, $option) as $shade) {
                        $colour = $option->shadeColorFor($shade);
                        if (isset($entry['shades'][$shade]) && $entry['shades'][$shade] !== $colour) {
                            $conflict = true;
                        } else {
                            $entry['shades'][$shade] = $colour;
                        }
                    }
                    if ($conflict) {
                        $where = $entry['site'] === $site ? "in two palettes on site $site" : "on sites {$entry['site']} and $site";
                        $this->warn("$labels[$framework]: \"$token\" has different colours $where. The first is used; give one swatch a distinct \"token\" in the config, or generate each site separately with --site.");
                    }
                    $entry['opacities'] = array_values(array_unique([...$entry['opacities'], ...$field->opacityOptionsForFramework($framework)]));
                    $data[$framework][$token] = $entry;
                }
            }
        }
        foreach ($data as $framework => $tokens) {
            foreach ($tokens as $token => $entry) {
                $order = array_flip(Frameworks::sortShades(array_map('strval', array_keys($entry['shades']))));
                uksort($entry['shades'], static fn($a, $b): int => $order[(string)$a] <=> $order[(string)$b]);
                sort($entry['opacities']);
                $data[$framework][$token] = $entry;
            }
            ksort($data[$framework], SORT_NATURAL);
        }
        ksort($data);
        return $data;
    }

    private function warn(string $message): void
    {
        $this->warnings[$message] = $message;
    }

    private function utilities(): array
    {
        return $this->settings->getSafelistUtilities();
    }

    /** @return array<string, int> */
    private static function opacities(array $tokens): array
    {
        $opacities = [];
        foreach ($tokens as $entry) {
            foreach ($entry['opacities'] as $opacity) {
                $opacities[$opacity] = $opacity;
            }
        }
        ksort($opacities);
        return $opacities;
    }

    /**
     * Tailwind's own colours (blue, red, …) have 50–950 but no base colour, so "theme => false" colours keep
     * Tailwind's shades and only define the base colour and any extra shades.
     */
    private static function tailwindTheme(string $framework, array $entry): array
    {
        $colours = ['' => $entry['stops'][0]];
        $defaults = Frameworks::defaultShades($framework);
        foreach ($entry['shades'] as $shade => $colour) {
            if ($entry['theme'] || !in_array((string)$shade, $defaults, true)) {
                $colours[(string)$shade] = $colour;
            }
        }
        return $colours;
    }

    private function tailwindPrefixes(): array
    {
        $utilities = $this->utilities();
        return array_values(array_filter([
            in_array('bg', $utilities, true) || in_array('textBg', $utilities, true) ? 'bg' : null,
            in_array('text', $utilities, true) ? 'text' : null,
            in_array('border', $utilities, true) ? 'border' : null,
        ]));
    }

    /** @return string[] */
    private function tailwindClasses(array $tokens): array
    {
        $classes = [];
        $prefixes = $this->tailwindPrefixes();
        foreach ($tokens as $token => $entry) {
            $names = [(string)$token, ...array_map(static fn($shade): string => "$token-$shade", array_keys($entry['shades']))];
            foreach ($prefixes as $prefix) {
                foreach ($names as $name) {
                    $classes[] = "$prefix-$name";
                    foreach ($entry['opacities'] as $opacity) {
                        $classes[] = "$prefix-$name/$opacity";
                    }
                }
            }
        }
        if (in_array('textBg', $this->utilities(), true) && $tokens !== []) {
            array_push($classes, 'text-white', 'text-black');
        }
        if (in_array('opacity', $this->utilities(), true)) {
            foreach (self::opacities($tokens) as $opacity) {
                $classes[] = "opacity-$opacity";
            }
        }
        return array_values(array_unique($classes));
    }

    private function tailwind3(array $tokens): array
    {
        $colours = [];
        foreach ($tokens as $token => $entry) {
            $theme = self::tailwindTheme(Frameworks::TAILWIND3, $entry);
            if ($theme !== []) {
                $map = [];
                foreach ($theme as $shade => $colour) {
                    $map[$shade === '' ? 'DEFAULT' : $shade] = $colour;
                }
                $colours[$token] = (object)$map;
            }
        }
        $opacity = [];
        foreach (self::opacities($tokens) as $value) {
            $opacity[(string)$value] = Frameworks::decimal($value);
        }
        $safelist = $this->tailwindClasses($tokens);
        $extend = array_filter(['colors' => (object)$colours, 'opacity' => (object)$opacity], static fn(object $value): bool => (array)$value !== []);
        $config = Json::encode([
            'theme' => ['extend' => (object)$extend],
            'safelist' => $safelist,
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        $js = '// ' . self::HEADER . "\n"
            . "// Use as a preset: presets: [require('./tailwind3.cjs')]. If your config has its own safelist, add ...require('./tailwind3.cjs').safelist to it.\n"
            . "module.exports = $config;\n";
        return [$js, count($safelist)];
    }

    private function tailwind4(array $tokens): array
    {
        $theme = [];
        $sources = [];
        $prefixes = $this->tailwindPrefixes();
        foreach ($tokens as $token => $entry) {
            foreach (self::tailwindTheme(Frameworks::TAILWIND4, $entry) as $shade => $colour) {
                $theme[] = '    --color-' . Frameworks::name((string)$token, $shade === '' ? null : (string)$shade) . ": $colour;";
            }
            if ($prefixes !== []) {
                $shades = ['', ...array_map(static fn($shade): string => "-$shade", array_keys($entry['shades']))];
                $opacities = ['', ...array_map(static fn(int $opacity): string => "/$opacity", $entry['opacities'])];
                $sources[] = self::braces($prefixes) . "-$token" . self::braces($shades) . self::braces($opacities);
            }
        }
        if (in_array('textBg', $this->utilities(), true) && $tokens !== []) {
            $sources[] = 'text-{white,black}';
        }
        $opacities = self::opacities($tokens);
        if (in_array('opacity', $this->utilities(), true) && $opacities !== []) {
            $sources[] = 'opacity-' . self::braces(array_map('strval', array_values($opacities)));
        }
        $css = '/* ' . self::HEADER . " */\n/* Import after Tailwind: @import \"tailwindcss\"; @import \"./tailwind4.css\"; */\n";
        if ($theme !== []) {
            $css .= "@theme {\n" . implode("\n", $theme) . "\n}\n";
        }
        foreach ($sources as $source) {
            $css .= "@source inline(\"$source\");\n";
        }
        return [$css, count($this->tailwindClasses($tokens))];
    }

    private static function braces(array $alternatives): string
    {
        return count($alternatives) === 1 ? $alternatives[0] : '{' . implode(',', $alternatives) . '}';
    }

    private function bootstrap5(array $tokens): array
    {
        $utilities = $this->utilities();
        $colourUtilities = ['bg' => 'background-color', 'text' => 'color', 'border' => 'border-color'];
        // Native Bootstrap classes for theme colours that support dark mode; redefining them would break it.
        $native = ['bg' => 'subtle', 'border' => 'subtle', 'text' => 'emphasis'];
        $maps = [];
        $textBg = [];
        $count = 0;
        foreach ($tokens as $token => $entry) {
            $colours = $entry['theme'] ? ['' => $entry['stops'][0]] : [];
            foreach ($entry['shades'] as $shade => $colour) {
                $colours[(string)$shade] = $colour;
            }
            foreach ($colours as $shade => $colour) {
                $name = Frameworks::name((string)$token, $shade === '' ? null : $shade);
                foreach ($colourUtilities as $utility => $property) {
                    if (in_array($utility, $utilities, true) && ($entry['theme'] || $native[$utility] !== $shade)) {
                        $value = Colour::withAlpha($colour, "--#{\$prefix}$utility-opacity");
                        $maps[$utility][] = "            \"$name\": string.unquote(\"$value\"),";
                        $count++;
                    }
                }
                if (in_array('textBg', $utilities, true)) {
                    $background = Colour::withAlpha($colour, '--#{$prefix}bg-opacity');
                    $textBg[] = ".text-bg-$name {\n    color: " . Colour::contrast($colour) . " !important;\n    background-color: string.unquote(\"$background\") !important;\n}";
                    $count++;
                }
            }
        }
        $opacities = self::opacities($tokens);
        $values = implode(', ', array_map(static fn(int $opacity): string => "$opacity: " . Frameworks::decimal($opacity), array_values($opacities)));
        $entries = [];
        foreach ($colourUtilities as $utility => $property) {
            if (isset($maps[$utility])) {
                $entries[] = "    \"mcs-$utility-color\": (\n        property: $property,\n        class: $utility,\n        local-vars: (\"$utility-opacity\": 1),\n        values: (\n"
                    . implode("\n", $maps[$utility]) . "\n        ),\n    ),";
            }
        }
        // Opacity utilities come after the colours so they override each colour's local opacity variable.
        if ($opacities !== []) {
            foreach (['bg' => ['bg', 'textBg'], 'text' => ['text'], 'border' => ['border']] as $utility => $requires) {
                if (array_intersect($requires, $utilities) !== []) {
                    $entries[] = "    \"mcs-$utility-opacity\": (\n        css-var: true,\n        class: $utility-opacity,\n        values: ($values),\n    ),";
                    $count += count($opacities);
                }
            }
            if (in_array('opacity', $utilities, true)) {
                $entries[] = "    \"mcs-opacity\": (\n        property: opacity,\n        values: ($values),\n    ),";
                $count += count($opacities);
            }
        }
        $scss = '// ' . self::HEADER . "\n"
            . "// Import after \"bootstrap/scss/utilities\" and before \"bootstrap/scss/utilities/api\",\n"
            . "// or before a single @import \"bootstrap/scss/bootstrap\".\n"
            . "@use \"sass:map\";\n"
            . "@use \"sass:string\";\n"
            . "\$prefix: \"bs-\" !default;\n"
            . "\$utilities: () !default;\n";
        if ($entries !== []) {
            $scss .= "\$utilities: map.merge(\n    \$utilities,\n    (\n" . implode("\n", array_map(static fn(string $entry): string => preg_replace('/^/m', '    ', $entry), $entries)) . "\n    )\n);\n";
        }
        if ($textBg !== []) {
            $scss .= "\n" . implode("\n\n", $textBg) . "\n";
        }
        return [$scss, $count];
    }

    private function pluginCss(array $tokens): array
    {
        $utilities = $this->utilities();
        $rules = [];
        foreach ($tokens as $token => $entry) {
            $colours = ['' => $entry['stops']];
            foreach ($entry['shades'] as $shade => $colour) {
                $colours[$shade] = [$colour];
            }
            foreach ($colours as $shade => $stops) {
                $name = Frameworks::name((string)$token, $shade === '' ? null : (string)$shade);
                foreach (['bg', 'text', 'border', 'textBg'] as $utility) {
                    if (in_array($utility, $utilities, true)) {
                        $rules[] = PluginCss::colourRule($utility, $name, $stops);
                    }
                }
            }
        }
        foreach (self::opacities($tokens) as $opacity) {
            foreach (['bg' => ['bg', 'textBg'], 'text' => ['text'], 'border' => ['border'], 'opacity' => ['opacity']] as $utility => $requires) {
                if (array_intersect($requires, $utilities) !== []) {
                    $rules[] = PluginCss::opacityRule($utility, $opacity);
                }
            }
        }
        $css = '/* ' . self::HEADER . " */\n/* Only needed when automatic CSS registration is turned off. */\n";
        if ($rules !== []) {
            $css .= PluginCss::PROPERTIES . "\n" . implode("\n", $rules) . "\n";
        }
        return [$css, count($rules)];
    }
}
